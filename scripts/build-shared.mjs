// Bundles the pure shared rules (src/shared/) into the Cloud Functions as
// CommonJS: functions/src/generated/shared.cjs (Phase 2, decision P2-A).
//
// One definition for the web and the functions: the web imports src/shared/
// directly; the functions `require('./generated/shared.cjs')`. The output is
// committed so the functions and their tests run without a build step, and
//   node scripts/build-shared.mjs --check
// fails when it is out of date (CI, and before every Functions deploy via
// firebase.json predeploy, which regenerates it first).
import { build } from 'esbuild'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outfile = path.join(root, 'functions', 'src', 'generated', 'shared.cjs')
const check = process.argv.includes('--check')

const result = await build({
  entryPoints: [path.join(root, 'src', 'shared', 'server.js')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  write: false,
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// GENERATED by scripts/build-shared.mjs from src/shared/ — do not edit.\n// Change src/shared/ and run `npm run build:shared`.' },
})
const code = result.outputFiles[0].text.replace(/\r\n/g, '\n')

if (check) {
  const current = existsSync(outfile) ? readFileSync(outfile, 'utf8').replace(/\r\n/g, '\n') : ''
  if (current !== code) {
    console.error('functions/src/generated/shared.cjs is out of date. Run `npm run build:shared` and commit it.')
    process.exit(1)
  }
  console.log('shared bundle is up to date')
} else {
  writeFileSync(outfile, code)
  console.log(`wrote ${path.relative(root, outfile)} (${code.length} bytes)`)
}
