// One-off generator: pulls barangays for Cotabato City + both Maguindanao
// provinces from the PSGC API and writes src/utils/barmm-barangays.js.
// The PSGC API still lists Maguindanao as one (pre-2022-split) province, so
// we re-split its municipalities into del Norte / del Sur using the same
// lists as utils/barmm.js. Run: node scripts/gen-barangays.mjs
import { writeFileSync } from 'node:fs'

const DEL_NORTE = [
  'Barira', 'Buldon', 'Datu Blah T. Sinsuat', 'Datu Odin Sinsuat',
  'Kabuntalan', 'Matanog', 'Northern Kabuntalan', 'Parang',
  'Sultan Kudarat', 'Sultan Mastura', 'Talitay', 'Upi',
]
const DEL_SUR = [
  'Ampatuan', 'Buluan', 'Datu Abdullah Sangki', 'Datu Anggal Midtimbang',
  'Datu Hoffer Ampatuan', 'Datu Montawal', 'Datu Paglas', 'Datu Piang',
  'Datu Salibo', 'Datu Saudi Ampatuan', 'Datu Unsay',
  'General Salipada K. Pendatun', 'Guindulungan', 'Mamasapano',
  'Mangudadatu', 'Pagalungan', 'Paglat', 'Pandag', 'Rajah Buayan',
  'Shariff Aguak', 'Shariff Saydona Mustapha', 'South Upi',
  'Sultan sa Barongis', 'Talayan',
]

// PSGC municipality code -> our canonical display name, for the few whose
// PSGC spelling differs from utils/barmm.js.
const CODE_ALIAS = {
  '153822000': 'Datu Montawal',                 // PSGC "Pagagawan"
  '153819000': 'General Salipada K. Pendatun',  // PSGC "Gen. s.k. Pendatun"
  '153826000': 'Datu Saudi Ampatuan',           // PSGC "Datu Saudi-Ampatuan"
  '153813000': 'Sultan sa Barongis',            // PSGC "Sultan Sa Barongis"
}

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '')
const CANON = [...DEL_NORTE, ...DEL_SUR]
const canonByNorm = Object.fromEntries(CANON.map(n => [norm(n), n]))

const toCanon = (code, psgcName) =>
  CODE_ALIAS[code] ?? canonByNorm[norm(psgcName)] ?? null

const getJSON = (url) => fetch(url).then(r => r.json())
const sortBgy = (arr) => [...arr].sort((a, b) => a.localeCompare(b))

const run = async () => {
  const munis = await getJSON('https://psgc.gitlab.io/api/provinces/153800000/cities-municipalities/')

  const norteOut = {}
  const surOut = {}
  let unmatched = []

  for (const m of munis) {
    const canon = toCanon(m.code, m.name)
    if (!canon) { unmatched.push(`${m.code} ${m.name}`); continue }
    const bgys = await getJSON(`https://psgc.gitlab.io/api/cities-municipalities/${m.code}/barangays/`)
    const names = sortBgy(bgys.map(b => b.name))
    if (DEL_NORTE.includes(canon)) norteOut[canon] = names
    else surOut[canon] = names
  }

  // Cotabato City (independent city, PSGC code 129804000)
  const ccBgys = await getJSON('https://psgc.gitlab.io/api/cities-municipalities/129804000/barangays/')
  const cotabato = { 'Cotabato City': sortBgy(ccBgys.map(b => b.name)) }

  if (unmatched.length) console.log('UNMATCHED MUNIS:', unmatched)

  const data = {
    'Maguindanao del Norte': norteOut,
    'Maguindanao del Sur': surOut,
    'Cotabato City': cotabato,
  }

  const total = Object.values(data).reduce((s, prov) =>
    s + Object.values(prov).reduce((t, arr) => t + arr.length, 0), 0)
  console.log('Provinces:', Object.keys(data).length,
    '| del Norte munis:', Object.keys(norteOut).length,
    '| del Sur munis:', Object.keys(surOut).length,
    '| total barangays:', total)

  const header = `// AUTO-GENERATED by scripts/gen-barangays.mjs from the PSGC API.
// Barangays for the CRMC mainland catchment: Cotabato City + both
// Maguindanao provinces. Keyed BARANGAYS[province][municipality] = [names].
// Municipalities/provinces not covered here fall back to free-text entry
// in the registration form. Do not edit by hand — re-run the generator.\n\n`
  const body = `export const BARANGAYS = ${JSON.stringify(data, null, 2)}\n`
  writeFileSync(new URL('../src/utils/barmm-barangays.js', import.meta.url), header + body)
  console.log('Wrote src/utils/barmm-barangays.js')
}

run().catch(e => { console.error('FAILED:', e.message); process.exit(1) })